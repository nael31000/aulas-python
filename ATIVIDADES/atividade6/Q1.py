#Crie um programa que exiba uma contagem regressiva para o lançamento de um foguete.
# O programa deve definir uma variável iniciando em 10 e, usando o while, exibir os números de 10 até 1. Ao final,
# quando o laço terminar, exiba a mensagem: "Foguete lançado!".


contagem = 10

while contagem >= 1:
    print(contagem)
    contagem -= 1
   

print("Foguete lançado!")